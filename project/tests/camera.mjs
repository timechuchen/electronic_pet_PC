import assert from 'node:assert/strict';
import fs from 'node:fs';
import { chromium } from 'playwright';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1200}});
const errors=[],external=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')console.log('CONSOLE',m.text().slice(0,250));});
page.on('request',r=>{if(/^https?:/.test(r.url())&&!r.url().startsWith('http://127.0.0.1:8765/'))external.push(r.url());});
const imageData='data:image/jpeg;base64,'+fs.readFileSync('tests/fixtures/pose.jpg').toString('base64');
const portrait='data:image/jpeg;base64,'+fs.readFileSync('tests/fixtures/portrait.jpg').toString('base64');
try {
  // Use a test-only canvas stream. No real camera or microphone is accessed.
  await page.addInitScript(({imageData,portrait})=>{
    window.testCamera={mode:'pose',calls:0,streams:[],deny:false,delay:0,frame:null};
    const images={};for(const [key,src] of Object.entries({pose:imageData,face:portrait})){images[key]=new Image();images[key].src=src;}
    Object.defineProperty(navigator.mediaDevices,'getUserMedia',{value:async()=>{
      window.testCamera.calls++;
      if(window.testCamera.deny)throw new DOMException('Test denied','NotAllowedError');
      if(window.testCamera.delay)await new Promise(resolve=>setTimeout(resolve,window.testCamera.delay));
      await Promise.all(Object.values(images).map(image=>image.decode()));
      const canvas=document.createElement('canvas');canvas.width=640;canvas.height=480;
      const ctx=canvas.getContext('2d');
      const paint=()=>{ctx.fillStyle='#fff';ctx.fillRect(0,0,640,480);const img=images[window.testCamera.mode];if(img){const scale=Math.min(640/img.width,480/img.height);const w=img.width*scale,h=img.height*scale;ctx.drawImage(img,(640-w)/2,(480-h)/2,w,h);}};
      paint();const timer=setInterval(paint,50);const stream=canvas.captureStream(20);
      window.testCamera.streams.push(stream);const original=stream.getTracks()[0].stop.bind(stream.getTracks()[0]);
      stream.getTracks()[0].stop=()=>{clearInterval(timer);original();};
      return stream;
    }});
  },{imageData,portrait});
  await page.goto('http://127.0.0.1:8765');
  await page.waitForFunction(()=>window.petDiagnostics?.().danceDuration,{timeout:60000});
  assert.equal(await page.evaluate(()=>window.testCamera.calls),0,'No automatic camera start');
  await page.locator('#camera-toggle').click();
  await page.waitForFunction(()=>['active','error'].includes(window.petDiagnostics().tracking.phase),{timeout:90000});
  console.log('status',await page.locator('#camera-status').textContent());
  assert.equal((await page.evaluate(()=>window.petDiagnostics())).tracking.phase,'active');
  await page.waitForFunction(()=>window.petDiagnostics().tracking.hasBody,{timeout:30000});
  await page.waitForTimeout(800);
  console.log('pose',JSON.stringify(await page.evaluate(()=>window.petDiagnostics())));
  const relayed=await page.evaluate(()=>fetch('/api/state').then(r=>r.json()));
  assert.ok(relayed.tracking?.bones?.rightUpperArm,'Camera pose relays to the local desktop service');
  assert.equal(await page.locator('[data-action=wave]').isDisabled(),true);
  assert.equal(await page.locator('#pause').isDisabled(),true);
  await page.screenshot({path:'screenshots/camera-pose.png',fullPage:true});
  const beforeLegs=await page.evaluate(()=>window.petDiagnostics().bones);
  await page.locator('#camera-legs').check();await page.waitForTimeout(500);
  const afterLegs=await page.evaluate(()=>window.petDiagnostics().bones);
  assert.ok(afterLegs.leftUpperLeg.some((v,i)=>Math.abs(v-beforeLegs.leftUpperLeg[i])>.1)||afterLegs.rightUpperLeg.some((v,i)=>Math.abs(v-beforeLegs.rightUpperLeg[i])>.1),'Full-body option moves legs');
  await page.screenshot({path:'screenshots/camera-legs.png',fullPage:true});
  await page.locator('#camera-legs').uncheck();
  await page.locator('#camera-calibrate').click();
  await page.evaluate(()=>window.testCamera.mode='face');
  await page.waitForFunction(()=>window.petDiagnostics().tracking.hasFace,{timeout:30000});
  await page.waitForTimeout(700);
  console.log('face',JSON.stringify(await page.evaluate(()=>window.petDiagnostics())));
  await page.screenshot({path:'screenshots/camera-face.png',fullPage:true});
  await page.evaluate(()=>window.testCamera.mode='blank');
  await page.waitForFunction(()=>!window.petDiagnostics().tracking.hasFace&&!window.petDiagnostics().tracking.hasBody,{timeout:10000});
  assert.match(await page.locator('#camera-status').textContent(),/进入画面/);
  await page.locator('#camera-toggle').click();
  assert.equal(await page.evaluate(()=>window.testCamera.streams.every(s=>s.getTracks().every(t=>t.readyState==='ended'))),true);
  assert.equal((await page.evaluate(()=>window.petDiagnostics())).tracking.phase,'idle');
  await page.locator('[data-action=wave]').click();
  await page.waitForFunction(()=>window.petDiagnostics().body?.name==='wave');
  await page.evaluate(()=>window.testCamera.deny=true);
  await page.locator('#camera-toggle').click();
  await page.waitForFunction(()=>window.petDiagnostics().tracking.phase==='error');
  assert.match(await page.locator('#camera-status').textContent(),/权限/);
  assert.equal(await page.locator('[data-action=wave]').isEnabled(),true);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'screenshots/camera-mobile.png',fullPage:true});
  await page.evaluate(()=>{window.testCamera.deny=false;window.testCamera.delay=500;});
  await page.locator('#camera-toggle').click();
  await page.waitForFunction(()=>window.petDiagnostics().tracking.phase==='loading');
  await page.locator('#camera-toggle').click();await page.waitForTimeout(900);
  assert.equal((await page.evaluate(()=>window.petDiagnostics())).tracking.phase,'idle');
  assert.equal(await page.evaluate(()=>window.testCamera.streams.every(s=>s.getTracks().every(t=>t.readyState==='ended'))),true,'Late permission must not leak camera');
  await page.evaluate(()=>{window.testCamera.delay=0;});
  await page.route('**/tracking/face_landmarker.task',route=>route.fulfill({status:404,body:'Test missing model'}));
  await page.locator('#camera-toggle').click();
  await page.waitForFunction(()=>window.petDiagnostics().tracking.phase==='error',{timeout:30000});
  assert.match(await page.locator('#camera-status').textContent(),/模型加载失败/);
  assert.equal(await page.evaluate(()=>window.testCamera.streams.every(s=>s.getTracks().every(t=>t.readyState==='ended'))),true,'Model failure releases stream');
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
  console.log('PASS: real local WASM inference with official pose/face images through simulated camera; no auto-start; mode exclusion; lost tracking; stop releases stream; denial; mobile; no uploads/external requests.');
}finally{await browser.close();}
